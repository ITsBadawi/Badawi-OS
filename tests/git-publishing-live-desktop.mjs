import { _electron as electron } from "playwright-core";
import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import assert from "node:assert/strict";

const owner = "itsbadawiit", repo = "badawi-os-parity-test-20261023";
const dir = await mkdtemp(path.join(tmpdir(), "badawi-live-git-"));
const checks = [], errors = [];
let app, page;
let token = execFileSync("gh", ["auth", "token", "--user", owner], { encoding: "utf8", windowsHide: true }).trim();
if (!token) throw Error("GITHUB_TEST_CREDENTIAL_MISSING");
const command = async (input) => {
  const response = await page.evaluate((value) => window.badawi.command(value), input);
  if (!response.ok) throw Error(response.error);
  return response.data;
};
try {
  const env = { ...process.env, BADAWI_DATA_DIR: path.join(dir, "data"), BADAWI_BACKGROUND: "1" };
  delete env.ELECTRON_RUN_AS_NODE;
  app = await electron.launch({ args: ["."], env });
  page = await app.firstWindow();
  page.setDefaultTimeout(20000);
  page.on("pageerror", (error) => errors.push(error.message));
  await page.getByRole("button", { name: "لوحة التحكم", exact: true }).waitFor();
  const workspace = await command({ op: "workspace.create", path: dir, inbox: false });
  await command({ op: "engine.mode", mode: "Running", epoch: (await command({ op: "snapshot" })).engine.epoch });
  await command({ op: "integration.save", integration: "github", token });
  token = "";
  const preview = await command({ op: "project.clone.preview", workspaceId: workspace.id, name: "Synthetic GitHub validation", folder: "synthetic-github-validation", github: { owner, repo } });
  assert.equal(preview.github.owner, owner);
  assert.equal(preview.github.repo, repo);
  const project = await command({ op: "project.clone.apply", previewId: preview.previewId });
  assert.equal(project.cloneReceipt.head, preview.remoteHead);
  checks.push("Private GitHub repository preview and actual authenticated clone succeeded in an isolated workspace");
  const proof = `Badawi OS synthetic Git acceptance ${new Date().toISOString()}\n`;
  await writeFile(path.join(project.root, "parity-proof.txt"), proof);
  await writeFile(path.join(project.root, "not-selected.txt"), "This must stay local and untracked.\n");
  await writeFile(path.join(project.root, ".env.local"), "synthetic-secret-must-stay-local\n");
  const changes = await command({ op: "git.changes", projectId: project.id });
  assert.equal(changes.changes.find((row) => row.path === ".env.local")?.blocked, true);
  const commitPreview = await command({ op: "git.commit.preview", projectId: project.id, paths: ["parity-proof.txt"], message: "Validate reviewed Badawi OS publish", authorName: "Badawi OS Test", authorEmail: "badawi-test@example.invalid" });
  assert.deepEqual(commitPreview.selected, ["parity-proof.txt"]);
  const committed = await command({ op: "git.commit.apply", previewId: commitPreview.previewId });
  assert.notEqual(committed.head, preview.remoteHead);
  checks.push("Exact synthetic file was locally committed; unselected and secret-like files remained outside the commit");
  const pushPreview = await command({ op: "git.push.preview", projectId: project.id });
  assert.equal(pushPreview.remoteHead, preview.remoteHead);
  assert.equal(pushPreview.localHead, committed.head);
  assert.equal(pushPreview.dirty, true);
  const pushed = await command({ op: "git.push.apply", previewId: pushPreview.previewId });
  assert.equal(pushed.head, committed.head);
  const remote = await command({ op: "github.check", projectId: project.id });
  assert.equal(remote.remoteHead, committed.head);
  assert.equal(remote.comparison.state, "identical");
  assert.equal(await readFile(path.join(project.root, "not-selected.txt"), "utf8"), "This must stay local and untracked.\n");
  checks.push("Actual GitHub Push was confirmed at the exact commit, with unselected and secret files still local");
  const state = await command({ op: "snapshot" });
  assert.ok(!JSON.stringify(state).includes("synthetic-secret-must-stay-local"));
  assert.deepEqual(errors, []);
  await command({ op: "integration.disconnect", integration: "github" });
  await writeFile("docs/validation/git-publishing-live-2026-10-24.json", JSON.stringify({ date: new Date().toISOString(), repository: `https://github.com/${owner}/${repo}`, private: true, checks, localHead: committed.head, remoteHead: remote.remoteHead, temporaryProfileRemoved: true, errors }, null, 2));
  console.log(JSON.stringify({ repository: `https://github.com/${owner}/${repo}`, checks, localHead: committed.head, remoteHead: remote.remoteHead, errors }));
} finally {
  token = "";
  if (app) await app.close();
  const target = path.resolve(dir), parent = path.resolve(tmpdir());
  if (path.dirname(target) !== parent) throw Error("TEST_CLEANUP_PATH_INVALID");
  await rm(target, { recursive: true, force: true });
}
