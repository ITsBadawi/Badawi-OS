import { _electron as electron } from "playwright-core";
import { execFileSync } from "node:child_process";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import assert from "node:assert/strict";

const dir = await mkdtemp(path.join(tmpdir(), "badawi-git-publishing-ui-"));
const gitBinary = path.join(process.env.ProgramFiles || "C:/Program Files", "Git/cmd/git.exe");
const checks = [], errors = [];
let app, page;
const command = async (input) => {
  const result = await page.evaluate((value) => window.badawi.command(value), input);
  if (!result.ok) throw Error(result.error);
  return result.data;
};
try {
  const env = { ...process.env, BADAWI_DATA_DIR: path.join(dir, "data"), BADAWI_BACKGROUND: "1" };
  delete env.ELECTRON_RUN_AS_NODE;
  app = await electron.launch({ args: ["."], env });
  page = await app.firstWindow();
  page.setDefaultTimeout(12000);
  page.on("pageerror", (error) => errors.push(error.message));
  await page.getByRole("button", { name: "لوحة التحكم", exact: true }).waitFor();
  const workspace = await command({ op: "workspace.create", path: dir, inbox: false });
  const initial = await command({ op: "snapshot" });
  await command({ op: "engine.mode", mode: "Running", epoch: initial.engine.epoch });
  const project = await command({ op: "project.create", workspaceId: workspace.id, name: "Git Publish Test", folder: "git-publish" });
  const git = (args) => execFileSync(gitBinary, args, { cwd: project.root, encoding: "utf8" }).trim();
  git(["init", "-b", "main"]);
  git(["config", "user.name", "Test Author"]);
  git(["config", "user.email", "test@example.invalid"]);
  await writeFile(path.join(project.root, "chosen.txt"), "first\n");
  await writeFile(path.join(project.root, "other.txt"), "first\n");
  git(["add", "chosen.txt", "other.txt"]);
  git(["commit", "-m", "Initial"]);
  const originalHead = git(["rev-parse", "HEAD"]);
  await writeFile(path.join(project.root, "chosen.txt"), "second\n");
  await writeFile(path.join(project.root, "other.txt"), "second\n");
  await writeFile(path.join(project.root, ".env.local"), "private-test-value\n");
  await page.getByRole("button", { name: "المشاريع", exact: true }).click();
  await page.getByRole("button").filter({ has: page.getByRole("heading", { name: "Git Publish Test", exact: true }) }).click();
  await page.getByRole("button", { name: "عرض الملفات المتغيرة", exact: true }).click();
  const chosen = page.locator("label.simple-task").filter({ hasText: "chosen.txt" });
  await chosen.waitFor();
  assert.equal(await page.locator("label.simple-task").filter({ hasText: ".env.local" }).locator("input").isDisabled(), true);
  const observation = await command({ op: "git.changes", projectId: project.id });
  await command({ op: "git.selection.propose", projectId: project.id, head: observation.head, statusHash: observation.statusHash, paths: ["chosen.txt"], explanation: "Include only chosen.txt" });
  await page.getByRole("button", { name: "عرض الملفات المتغيرة", exact: true }).click();
  await page.getByText("Include only chosen.txt").waitFor();
  assert.equal(await chosen.locator("input").isChecked(), true);
  assert.equal(await page.locator("label.simple-task").filter({ hasText: "other.txt" }).locator("input").isChecked(), false);
  await chosen.locator("input").uncheck();
  await chosen.locator("input").check();
  await page.getByLabel("وصف Commit", { exact: true }).fill("Selected change");
  await page.getByRole("button", { name: "معاينة Commit", exact: true }).click();
  await page.getByRole("heading", { name: "راجع الحفظ المحلي", exact: true }).waitFor();
  assert.equal(git(["rev-parse", "HEAD"]), originalHead);
  const review = page.getByRole("heading", { name: "راجع الحفظ المحلي" }).locator("..");
  assert.match(await review.innerText(), /chosen\.txt/);
  assert.doesNotMatch(await review.innerText(), /other\.txt/);
  checks.push("Native file picker shows recent changes, blocks secret paths and previews only selected files without committing");
  await page.getByRole("button", { name: "أوافق، احفظ Commit المحلي", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "حُفظ Commit المحلي" }).waitFor();
  const committed = git(["rev-parse", "HEAD"]);
  assert.notEqual(committed, originalHead);
  assert.deepEqual(git(["show", "--pretty=format:", "--name-only", "HEAD"]).split(/\r?\n/).filter(Boolean), ["chosen.txt"]);
  assert.match(git(["status", "--porcelain"]), /other\.txt/);
  checks.push("Native approval creates only the chosen local commit and preserves unselected work");
  await command({ op: "project.details", id: project.id, name: project.name, github: { owner: "owner", repo: "repo", branch: "main" } });
  await command({ op: "integration.save", integration: "github", token: "controlled-token" });
  await app.evaluate((_, { head }) => {
    globalThis.__badawiRequests = [];
    globalThis.__fixtureHead = head;
    globalThis.fetch = async (url) => {
      globalThis.__badawiRequests.push(String(url));
      if (!String(url).startsWith("https://api.github.com/repos/owner/repo")) throw Error("Unexpected endpoint");
      if (String(url).includes("/compare/")) return Response.json({ message: "not found" }, { status: 404 });
      if (String(url).includes("/commits/")) return Response.json({ sha: head });
      return Response.json({ id: 1, private: true, archived: false, default_branch: "main", size: 1 });
    };
  }, { head: originalHead });
  const directPush = await command({ op: "git.push.preview", projectId: project.id });
  assert.equal(directPush.localHead, committed);
  await page.getByRole("button", { name: "معاينة الرفع إلى GitHub", exact: true }).click();
  const push = page.getByRole("heading", { name: "راجع الرفع إلى GitHub", exact: true });
  await push.waitFor();
  const detail = await push.locator("..").innerText();
  assert.match(detail, /owner\/repo/);
  assert.match(detail, new RegExp(committed));
  assert.match(detail, new RegExp(originalHead));
  assert.equal(git(["rev-parse", "HEAD"]), committed);
  checks.push("Push has a distinct native review bound to linked repository, branch and exact local and remote commits");
  assert.deepEqual(errors, []);
  await writeFile("docs/validation/git-publishing-desktop.json", JSON.stringify({ date: new Date().toISOString(), checks, errors, livePush: false }, null, 2));
  console.log(JSON.stringify({ checks, errors }));
} finally {
  if (app) await app.close();
  await rm(dir, { recursive: true, force: true });
}
